/**
 * Односторонний нижний CUSUM — пожизненный надзор за выпускниками.
 *
 * Каждая закрытая сделка выпускника стандартизуется против эталонного
 * распределения, замороженного в момент выпуска (μ_ref, σ_ref из инкубации),
 * и кормит кумулятивную сумму. k=0.5 (настроен на сдвиг в 1σ), h=5:
 * деградацию в 1σ ловит примерно за 10 сделок, ложная тревога на здоровой
 * стратегии — раз в ≈930 сделок (односторонняя таблица NIST; двусторонняя
 * цифра Монтгомери 465 — НЕ наша схема).
 *
 * Смысл: edge умирает (в среднем живёт 1–2 года), и решение «когда снимать»
 * принято ДО просадки, а не во время неё.
 */

export const CUSUM_K = 0.5;
export const CUSUM_H = 5;

export interface CusumResult {
  /** Текущее значение суммы после последней сделки. */
  s: number;
  /** Номер сделки первой тревоги (1-based); 0 — тревоги не было. */
  alarmAt: number;
  /** Максимум суммы за всю серию — «насколько близко подходили». */
  max: number;
}

/**
 * Нижний CUSUM по стандартизованным доходностям: здоровый поток (z≈0)
 * прижимает сумму к нулю, деградация копит её вверх до порога h.
 */
export function cusumLower(
  zScores: readonly number[],
  k: number = CUSUM_K,
  h: number = CUSUM_H,
): CusumResult {
  let s = 0;
  let max = 0;
  let alarmAt = 0;
  for (let i = 0; i < zScores.length; i++) {
    s = Math.max(0, s - zScores[i] - k);
    if (s > max) max = s;
    if (alarmAt === 0 && s > h) alarmAt = i + 1;
  }
  return { s, alarmAt, max };
}
