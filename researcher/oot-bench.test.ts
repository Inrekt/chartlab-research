import { describe, expect, test } from "vitest";
import { runOotBench } from "./oot-bench.ts";

/**
 * Стенд гоняет РЕАЛЬНЫЙ корпус, поэтому тесты держатся за свойства, которые
 * не зависят от конкретных цен: исполнимость пути и знак вывода. Числа
 * (проценты, медианы) живут в пре-регистрации, а не в ассертах — иначе
 * обновление корпуса красило бы тесты в красный без единой ошибки в коде.
 */
describe("стенд ворот out-of-time", () => {
  test("путь исполняется без исключений — до этого он не запускался НИ РАЗУ", () => {
    // За 56 374 испытания в журнале ноль записей gate_oot: их всегда убивала
    // дефляция раньше. Первый живой кандидат стал бы бета-тестером боевого
    // кода в худший возможный момент.
    const row = runOotBench({ n: 6, tf: "4h", seed: 3, symbols: 4 });
    expect(row.attempted).toBe(6);
    expect(row.judged + row.tooFewDays).toBeLessThanOrEqual(6);
    expect(Number.isFinite(row.medianOotTrades)).toBe(true);
  }, 120_000);

  test("нуль-модель НЕ смещена в пользу кандидата — контрольный опыт", () => {
    // Ключевой тест проекта на сегодня. По журналу среди 1512 отвергнутых
    // кандидатов нет ни одного отрицательного t, и это выглядело как
    // сломанный базлайн. Но до нуль-модели доходят только кандидаты, уже
    // отобранные за прибыльность в ЭТОМ ЖЕ окне — активностью, широтой,
    // стрессом издержек и плато.
    //
    // Контроль: неотобранные кандидаты в том же окне. Если машинерия
    // смещена — отрицательных не будет и здесь. Замер даёт около 90%,
    // то есть смещения нет, а журнальный перекос объясняется ОТБОРОМ.
    const row = runOotBench({ n: 8, tf: "4h", seed: 3, symbols: 4, window: "in" });
    if (row.judged >= 4) {
      expect(row.negativeTShare).toBeGreaterThan(0.4);
      expect(row.medianT).toBeLessThan(1);
    }
  }, 120_000);
});
