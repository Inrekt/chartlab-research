/**
 * FNV-1a, 32 бита — единственная хэш-функция исследователя для всех
 * детерминированных разбиений (отложенные символы, порядок деления,
 * корзины ширины). Вынесена из corpus.ts, чтобы чистые ворота (gates.ts)
 * могли ею пользоваться, не таща за собой чтение корпуса с диска.
 */
export function fnv1a(text: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < text.length; i++) {
    h ^= text.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h >>> 0;
}
