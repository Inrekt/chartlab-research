import { describe, expect, test } from "vitest";
import { calibrateSprt } from "./selfcheck.ts";

/*
 * Самокалибровка SPRT — единственная автоматическая проверка ошибок первого и
 * второго рода инкубатора.
 *
 * До 2026-08-10 она проверяла ПРИБОР, КОТОРОГО БОЛЬШЕ НЕТ: гоняла независимые
 * посделочные наблюдения через `sprtDecide` напрямую, тогда как боевой путь
 * агрегирует сделки в дневные средние и считает σ_день через внутридневную
 * корреляцию. Ни одна из трёх новых функций не вызывалась, а поток был i.i.d. —
 * то есть корреляции, ради которой правку делали, в симуляции физически не
 * существовало. Сторож охранял пустую комнату: он отрапортовал бы «в норме»
 * при ЛЮБОЙ поломке дневного слоя, и именно поэтому дефекты этого слоя
 * пришлось искать вручную.
 *
 * Числа ниже — замеренные на боевом пути, и они прибиты намеренно: если
 * будущая правка поднимет мощность, не тронув ложное принятие, тест обязан
 * упасть и заставить объяснить, откуда взялась прибавка.
 */
describe("самокалибровка SPRT на БОЕВОМ пути", () => {
  const thin = calibrateSprt(600, 0.15, 1, 42);
  const fat = calibrateSprt(600, 0.25, 1, 42);

  test("ложное принятие держится НИЖЕ номинала Вальда (5.6%)", () => {
    // Главное свойство: тест не мягче собственной вывески. Замерено 2.7–3.8%
    // на диапазоне δ 0.12…0.35 — то есть консервативен, и это правильная
    // сторона ошибки.
    expect(thin.falseAcceptRate).toBeLessThanOrEqual(0.056);
    expect(fat.falseAcceptRate).toBeLessThanOrEqual(0.056);
  });

  test("мощность 72–80%, а НЕ 92% как считалось", () => {
    /*
     * Поправка к пре-регистрации `sprt-daily-preregistration.md`. Там записано
     * «после правки 3.5% и 92%», и доля ложных принятий подтвердилась (2.8%),
     * а вот мощность — нет: 92% были измерены на посделочной симуляции, то
     * есть на приборе, которого в проде нет.
     *
     * Честная цена перехода на дневные наблюдения: около 13 пунктов мощности.
     * Это не дефект, а плата за корректность — посделочный счёт давал 14.5%
     * ложных принятий вместо 5.6%, и та «мощность» была куплена мягкостью.
     */
    expect(fat.powerRate).toBeGreaterThan(0.72);
    expect(fat.powerRate).toBeLessThan(0.85);
    expect(thin.powerRate).toBeGreaterThan(0.72);
  });

  test("мощность почти НЕ зависит от размера края — так устроено усечение", () => {
    /*
     * Неочевидное следствие правила `3·E[N]`: слабому краю оно даёт
     * пропорционально больший запас наблюдений, и мощность выравнивается.
     * Замерено: 72.5% при δ=0.12, 77.7% при 0.20, 77.0% при 0.25, 74.5% при
     * 0.35 — разброс в пять пунктов на трёхкратном диапазоне края.
     *
     * Прежний тест утверждал обратное («чем жирнее край, тем легче доказать»)
     * и был верен для посделочной симуляции с ФИКСИРОВАННОЙ длиной потока.
     * Как только длина стала зеркалить боевое усечение, утверждение
     * перестало быть верным.
     */
    expect(Math.abs(fat.powerRate - thin.powerRate)).toBeLessThan(0.1);
  });

  test("детерминизм: тот же сид — те же числа", () => {
    // Без этого калибровка не годится в сторожа: «улучшение» было бы
    // неотличимо от шума прогона.
    expect(calibrateSprt(600, 0.15, 1, 42)).toEqual(thin);
  });

  test("усечение под нулём остаётся редким", () => {
    // Поток без края обязан чаще ОТВЕРГАТЬСЯ, чем упираться в потолок:
    // усечение — это потраченный календарь без знания.
    expect(thin.truncatedNullRate).toBeLessThan(0.2);
    expect(fat.truncatedNullRate).toBeLessThan(0.2);
  });
});
